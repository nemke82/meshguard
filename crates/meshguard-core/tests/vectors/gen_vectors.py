#!/usr/bin/env python3
"""Independent reference implementation of the MeshGuard v1/v2 wire formats.

Generates the known-answer vectors in `vectors.rs` without using any Rust
code, so the Rust codec is checked against a second implementation (and a
future Kotlin/Android implementation can be checked against the same bytes).

    pip install cryptography
    python3 -I crates/meshguard-core/tests/vectors/gen_vectors.py > \
        crates/meshguard-core/tests/vectors/vectors.rs
"""
import hashlib
import struct

from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.kdf.hkdf import HKDF


def derive_p2p_key(me: str, peer: str, passphrase: str) -> bytes:
    a, b = sorted([me.strip(), peer.strip()])
    ikm = hashlib.sha256(
        a.encode() + b"|" + b.encode() + b"|" + passphrase.encode()
    ).digest()
    return HKDF(
        algorithm=hashes.SHA256(),
        length=32,
        salt=b"meshguard-p2p-v1",
        info=b"aes-256-gcm-p2p-key",
    ).derive(ikm)


def v1_frame(key: bytes, msg_type: int, text: str, nonce: bytes) -> bytes:
    return nonce + AESGCM(key).encrypt(nonce, bytes([msg_type]) + text.encode(), None)


def meshtastic_identity(node: int) -> bytes:
    return b"M" + struct.pack(">I", node)


def aad_context(sender: bytes, recipient: bytes) -> bytes:
    return (
        struct.pack(">H", len(sender)) + sender
        + struct.pack(">H", len(recipient)) + recipient
    )


def v2_frame(key, msg_type, msg_id, created_at, ttl_mins, body, context, nonce):
    inner = bytes([2, msg_type]) + msg_id + struct.pack(">IH", created_at, ttl_mins) + body
    return b"MG2" + nonce + AESGCM(key).encrypt(nonce, inner, b"MG2" + context)


def const(name: str, value: bytes) -> str:
    return f'pub const {name}: &str = "{value.hex()}";'


key = derive_p2p_key("Alice", "Bob", "secret")
ctx = aad_context(meshtastic_identity(1), meshtastic_identity(2))

lines = [
    "// @generated by gen_vectors.py — do not edit by hand.",
    "// Key: derive_p2p_key(\"Alice\", \"Bob\", \"secret\").",
    "// v2 context: aad_context(meshtastic_node(1), meshtastic_node(2)).",
    "#[allow(dead_code)]",
    "pub mod vectors {",
    "    " + const("V1_TEXT_FRAME_HEX", v1_frame(key, 0x01, "Hello mesh", bytes(range(12)))),
    "    " + const("V1_PAIR_REQUEST_FRAME_HEX", v1_frame(key, 0x02, "Alice-Radio", bytes(range(12, 24)))),
    "    " + const("V1_MULTIBYTE_TEXT_FRAME_HEX", v1_frame(key, 0x01, "Zdravo 👋 ćao", bytes(range(24, 36)))),
    "    " + const("V2_TEXT_FRAME_HEX", v2_frame(
        key, 0x01, b"0123456789abcdef", 1763100000, 60,
        "Zdravo 👋".encode(), ctx, b"\x11" * 12)),
    "    " + const("V2_ACK_FRAME_HEX", v2_frame(
        key, 0x10, b"fedcba9876543210", 1763100005, 10,
        b"0123456789abcdef", ctx, b"\x22" * 12)),
    "}",
    "pub use vectors::*;",
]
print("\n".join(lines))
